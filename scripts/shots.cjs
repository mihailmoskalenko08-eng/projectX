// Скриншоты экранов: npm run build && npx vite preview --port 4173 & node scripts/shots.cjs [out] [dark|light]
const { chromium, devices } = require('playwright')
;(async () => {
  const out = process.argv[2] || 'shots-tmp'
  const theme = process.argv[3] || 'dark'
  const scale = +(process.argv[4] || 1)
  require('node:fs').mkdirSync(out, { recursive: true })
  const b = await chromium.launch()
  const ctx = await b.newContext({ ...devices['iPhone 15 Pro'], deviceScaleFactor: scale, colorScheme: theme })
  const p = await ctx.newPage()
  const errors = []
  p.on('pageerror', e => errors.push(e.message))
  p.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  const URL = 'http://localhost:4173/projectX/'
  const snap = async (name, full = false) => { await p.waitForTimeout(1500); await p.screenshot({ path: `${out}/${name}.png`, fullPage: full }) }
  await p.goto(URL)
  await p.evaluate(() => localStorage.clear())
  await p.reload()
  await snap('0-onboarding')
  await p.getByText('Посмотреть на примере').click()
  await snap('1-home')
  await snap('1-home-full', true)
  await p.locator('.tab', { hasText: 'Операции' }).click()
  await snap('2-ops')
  await p.locator('.tab', { hasText: 'Аналитика' }).click()
  await snap('3-stats')
  await snap('3-stats-full', true)
  await p.locator('.tab', { hasText: 'Ещё' }).click()
  await snap('4-more-full', true)
  await p.locator('.fab').click()
  await p.waitForTimeout(500)
  for (const k of ['1', '2', ',', '5']) await p.locator('.key', { hasText: k }).first().click()
  await p.locator('.cat-cell').nth(1).click()
  await snap('5-add')
  await p.locator('.btn-primary', { hasText: 'Готово' }).click()
  await p.waitForTimeout(600)
  await p.locator('.tab', { hasText: 'Главная' }).click()
  await p.waitForTimeout(800)
  await p.locator('.tx').first().click()
  await snap('6-tx')
  await p.keyboard.press('Escape')
  await p.waitForTimeout(500)
  await p.locator('.tab', { hasText: 'Ещё' }).click()
  await p.waitForTimeout(400)
  await p.getByText('Траты из SMS').first().click()
  await snap('7-sync')
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors')
  await b.close()
})()
